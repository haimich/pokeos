export function topicLines(key) {
  const t = TOPICS[key]
  const body = typeof t.lines === 'function' ? t.lines() : t.lines
  return [
    `{h|━━ ${t.title} ━━}  {d|man 7 ${key}}`,
    ...body,
    '',
    `{d|try:} ${t.try.map((c) => `{$|${c}}`).join('{d| · }')}` + (t.quiz ? `   {d|quiz:} {$|play ${t.quiz}}` : ''),
  ]
}
